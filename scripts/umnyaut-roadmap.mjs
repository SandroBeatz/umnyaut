function body(todo, done, ref) {
  const out = [];
  if (todo?.length) out.push('**Что сделать**', ...todo.map((x) => `- ${x}`), '');
  if (done?.length) out.push('**Готово, когда**', ...done.map((x) => `- ${x}`), '');
  if (ref) out.push(`_Бизнес-спека: ${ref}_`);
  return out.join('\n').trim();
}

/** Обычная задача. */
function t(stage, area, title, start, end, todo, done, ref) {
  return { stage, area, title, start, end, body: body(todo, done, ref) };
}

/** Контрольная точка: условие перехода между этапами. */
function gate(stage, date, title, condition, otherwise, ref) {
  return {
    stage,
    area: 'Контрольная точка',
    title: `◆ ${title}`,
    start: date,
    end: date,
    body: [
      '**Условие «идём дальше»**',
      ...condition.map((x) => `- ${x}`),
      '',
      '**Если не выполнено**',
      ...otherwise.map((x) => `- ${x}`),
      '',
      `_Бизнес-спека: ${ref}_`,
    ].join('\n'),
  };
}

/** Калькулятор из каталога (раздел 8). */
function calc(stage, wave, name, size, start, end, query, extra, input, output, note) {
  const needsScheme = /схема/i.test(output);
  return {
    stage,
    area: 'Калькуляторы',
    size,
    title: `Калькулятор: ${name}`,
    start,
    end,
    body: [
      `Волна ${wave} · сложность ${size} · главный запрос: ${query}`,
      '',
      `**Что считает сверх формулы:** ${extra}`,
      `**Вход:** ${input}`,
      `**Результат:** ${output}`,
      ...(note ? ['', `**Важно:** ${note}`] : []),
      '',
      '**Готово, когда**',
      '- Выполнены требования 1–14 стандарта калькулятора (единицы покупки, запас, проёмы, сопутствующие материалы, стоимость, предупреждения, «Как посчитано», источник норм, перенос комнаты, сохранить и отправить)',
      ...(needsScheme
        ? ['- Есть схема, которая перестраивается при изменении параметров (требование 15)']
        : []),
      '- Пресеты типовых размеров и продуктов там, где у материала есть стандартные форматы (требование 16)',
      '- Десять эталонных примеров в тестах, сверка с двумя-тремя конкурентами',
      '- Текст под инструментом 300–600 слов: как считается, запас, пример, частые ошибки, 5–8 вопросов из запросов',
      '- Работают связки «дальше по ремонту» с перенесёнными размерами',
      '',
      `_Бизнес-спека: раздел 8 (волна ${wave}), стандарт — раздел 7_`,
    ].join('\n'),
  };
}

