export const QUERIES = {
  project: `query($owner:String!,$number:Int!){
    user(login:$owner){ projectV2(number:$number){
      id title url
      fields(first:100){ nodes{
        ... on ProjectV2Field { id name dataType }
        ... on ProjectV2IterationField { id name dataType }
        ... on ProjectV2SingleSelectField { id name dataType options { id name } }
      } }
    } }
  }`,
  items: `query($id:ID!,$after:String){
    node(id:$id){ ... on ProjectV2 { items(first:100, after:$after){
      pageInfo{ hasNextPage endCursor }
      nodes{ id type content{
        ... on DraftIssue { title body }
        ... on Issue { title number url }
        ... on PullRequest { title number url }
      } }
    } } }
  }`,
  deleteItem: `mutation($project:ID!,$item:ID!){
    deleteProjectV2Item(input:{projectId:$project,itemId:$item}){ deletedItemId }
  }`,
  createField: `mutation($input:CreateProjectV2FieldInput!){
    createProjectV2Field(input:$input){ projectV2Field{
      ... on ProjectV2Field { id name dataType }
      ... on ProjectV2SingleSelectField { id name dataType options { id name } }
    } }
  }`,
  deleteField: `mutation($field:ID!){
    deleteProjectV2Field(input:{fieldId:$field}){ clientMutationId }
  }`,
  addDraft: `mutation($project:ID!,$title:String!,$body:String){
    addProjectV2DraftIssue(input:{projectId:$project,title:$title,body:$body}){ projectItem{ id } }
  }`,
  addItem: `mutation($project:ID!,$content:ID!){
    addProjectV2ItemById(input:{projectId:$project,contentId:$content}){ item{ id } }
  }`,
};

/** Одна мутация, выставляющая n полей задачи сразу. */
export function setFieldsMutation(n) {
  const vars = ['$project:ID!', '$item:ID!'];
  const parts = [];
  for (let i = 0; i < n; i++) {
    vars.push(`$f${i}:ID!`, `$v${i}:ProjectV2FieldValue!`);
    parts.push(
      `s${i}: updateProjectV2ItemFieldValue(input:{projectId:$project,itemId:$item,fieldId:$f${i},value:$v${i}}){ clientMutationId }`
    );
  }
  return `mutation(${vars.join(',')}){ ${parts.join(' ')} }`;
}

// ───────────────────────────── gh ─────────────────────────────

function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

function fail(msg) {
  console.error(`\n✖ ${msg}`);
  process.exit(1);
}

function gh(args, input) {
  const res = spawnSync('gh', args, { input, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (res.error?.code === 'ENOENT')
    fail('Не найден GitHub CLI. Установи его: https://cli.github.com');
  if (res.error) throw res.error;
  return res;
}

function gql(query, variables = {}) {
  const waits = [2000, 6000, 20000];
  for (let attempt = 0; ; attempt++) {
    const res = gh(['api', 'graphql', '--input', '-'], JSON.stringify({ query, variables }));
    let json = null;
    try {
      json = JSON.parse(res.stdout);
    } catch {
      /* ответ не JSON — разберём ниже */
    }
    if (json?.data && !json.errors?.length) return json.data;
    const message =
      json?.errors?.map((e) => e.message).join('; ') ||
      json?.message ||
      res.stderr.trim() ||
      'неизвестная ошибка';
    if (
      /INSUFFICIENT_SCOPES|required scopes|has not been granted the required scopes/i.test(
        message + res.stderr
      )
    ) {
      fail(
        'Токену gh не хватает права на проекты. Выполни:  gh auth refresh -s project  — и запусти скрипт снова.'
      );
    }
    const transient =
      /rate limit|secondary|abuse|timeout|timed out|something went wrong|50[234]/i.test(message);
    if (transient && attempt < waits.length) {
      console.log(
        `  … GitHub просит подождать (${message}); повтор через ${waits[attempt] / 1000} с`
      );
      sleep(waits[attempt]);
      continue;
    }
    throw new Error(message);
  }
}

function rest(args, payload) {
  const res = gh(
    ['api', ...args, ...(payload ? ['--input', '-'] : [])],
    payload ? JSON.stringify(payload) : undefined
  );
  if (res.status !== 0) throw new Error(res.stderr.trim() || res.stdout.trim());
  return res.stdout;
}

// ───────────────────────────── Шаги ─────────────────────────────

function loadProject() {
  const data = gql(QUERIES.project, { owner: OWNER, number: PROJECT_NUMBER });
  const project = data.user?.projectV2;
  if (!project)
    fail(`Проект ${OWNER}/projects/${PROJECT_NUMBER} не найден или недоступен этому аккаунту gh.`);
  project.fields = project.fields.nodes.filter((f) => f?.id);
  return project;
}

function loadItems(projectId) {
  const items = [];
  let after = null;
  do {
    const page = gql(QUERIES.items, { id: projectId, after }).node.items;
    items.push(...page.nodes);
    after = page.pageInfo.hasNextPage ? page.pageInfo.endCursor : null;
  } while (after);
  return items;
}

function fieldIsFine(def, existing) {
  if (!existing || existing.dataType !== def.type) return false;
  if (def.type !== 'SINGLE_SELECT') return true;
  const have = new Set(existing.options.map((o) => o.name));
  return def.options.every((o) => have.has(o.name));
}

function ensureFields(project) {
  const byName = new Map(project.fields.map((f) => [f.name, f]));
  const result = new Map();
  for (const def of FIELD_DEFS) {
    let field = byName.get(def.name);
    if (field && !fieldIsFine(def, field)) {
      console.log(`  поле «${def.name}» есть, но не подходит — пересоздаю`);
      gql(QUERIES.deleteField, { field: field.id });
      field = null;
    }
    if (!field) {
      const input = { projectId: project.id, dataType: def.type, name: def.name };
      if (def.options) input.singleSelectOptions = def.options;
      field = gql(QUERIES.createField, { input }).createProjectV2Field.projectV2Field;
      console.log(`  создано поле «${def.name}»`);
    } else {
      console.log(`  поле «${def.name}» уже есть`);
    }
    result.set(def.name, field);
  }
  return result;
}

function pickStatus(project) {
  const status = project.fields.find((f) => f.name === 'Status' && f.dataType === 'SINGLE_SELECT');
  if (!status?.options?.length) return null;
  const option =
    status.options.find((o) =>
      /^(todo|to do|backlog|к выполнению|запланировано)$/i.test(o.name.trim())
    ) ?? status.options[0];
  return { fieldId: status.id, optionId: option.id, name: option.name };
}

function existingIssues(repo) {
  const out = rest([
    `repos/${repo}/issues?state=all&per_page=100`,
    '--paginate',
    '--jq',
    '.[] | select(.pull_request == null) | [.node_id, .number, .title] | @json',
  ]);
  const map = new Map();
  for (const line of out.split('\n').filter(Boolean)) {
    const [nodeId, number, title] = JSON.parse(line);
    if (!map.has(title)) map.set(title, { nodeId, number });
  }
  return map;
}

function ensureLabel(repo) {
  const res = gh(['api', `repos/${repo}/labels/${encodeURIComponent(BUSINESS_LABEL.name)}`]);
  if (res.status === 0) return;
  rest([`repos/${repo}/labels`], BUSINESS_LABEL);
  console.log(`  создана метка «${BUSINESS_LABEL.name}» в ${repo}`);
}

function addLabel(repo, number) {
  rest([`repos/${repo}/issues/${number}/labels`], { labels: [BUSINESS_LABEL.name] });
}

function optionId(field, name) {
  const option = field.options.find((o) => o.name === name);
  if (!option) throw new Error(`В поле «${field.name}» нет варианта «${name}»`);
  return option.id;
}

function describeItem(item) {
  const c = item.content ?? {};
  const kind =
    { DRAFT_ISSUE: 'черновик', ISSUE: 'issue', PULL_REQUEST: 'pull request', REDACTED: 'скрыто' }[
      item.type
    ] ?? item.type;
  return `[${kind}] ${c.title ?? '(без названия)'}${c.number ? ` #${c.number}` : ''}`;
}

// ───────────────────────────── Markdown ─────────────────────────────

function ruDate(iso) {
  const [y, m, d] = iso.split('-');
  return `${d}.${m}.${y}`;
}

export function toMarkdown() {
  const stages = STAGE_OPTIONS();
  const out = [
    '# UmnyAut — роудмап и задачи',
    '',
    `Бизнес-спецификация, разложенная на задачи (всего ${TASKS.length}) для GitHub Project https://github.com/users/${OWNER}/projects/${PROJECT_NUMBER}.`,
    'Границы этапов и контрольные точки взяты из спеки (разделы 4 и 14); даты отдельных задач внутри этапа — рабочая раскладка под 8–10 часов в неделю, её можно двигать.',
    '',
  ];
  for (const stage of stages) {
    const list = TASKS.filter((x) => x.stage === stage.name);
    out.push(
      `## ${stage.name} (${stage.description})`,
      '',
      '| Задача | Область | Начало | Срок | Размер |',
      '| --- | --- | --- | --- | --- |'
    );
    for (const x of list)
      out.push(
        `| ${x.title} | ${x.area} | ${ruDate(x.start)} | ${ruDate(x.end)} | ${x.size ?? ''} |`
      );
    out.push('');
  }
  return out.join('\n');
}

// ───────────────────────────── Запуск ─────────────────────────────

function validateTasks() {
  const stageNames = new Set(STAGE_OPTIONS().map((o) => o.name));
  const areaNames = new Set(fieldDef(F_AREA).options.map((o) => o.name));
  const titles = new Set();
  for (const x of TASKS) {
    if (!stageNames.has(x.stage)) throw new Error(`Неизвестный этап: ${x.title}`);
    if (!areaNames.has(x.area)) throw new Error(`Неизвестная область: ${x.title}`);
    if (
      !/^\d{4}-\d{2}-\d{2}$/.test(x.start) ||
      !/^\d{4}-\d{2}-\d{2}$/.test(x.end) ||
      x.start > x.end
    )
      throw new Error(`Неверные даты: ${x.title}`);
    if (titles.has(x.title)) throw new Error(`Повтор названия: ${x.title}`);
    titles.add(x.title);
  }
}

function main() {
  const argv = process.argv.slice(2);
  const flag = (name) => argv.includes(name);
  const value = (name) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : null);
  validateTasks();

  if (flag('--md')) {
    const file = value('--md') || 'umnyaut-roadmap.md';
    writeFileSync(file, toMarkdown());
    console.log(`Роудмап записан в ${file}`);
    return;
  }

  const apply = flag('--apply');
  const keepOld = flag('--keep-old');
  const repo = value('--repo');
  if (flag('--repo') && !/^[\w.-]+\/[\w.-]+$/.test(repo ?? ''))
    fail('Формат: --repo владелец/репозиторий');

  const project = loadProject();
  const oldItems = loadItems(project.id);
  console.log(`Проект: «${project.title}» — ${project.url}`);
  console.log(
    `\nСтарых задач в проекте: ${oldItems.length}${keepOld ? ' (останутся: --keep-old)' : ' — будут удалены'}`
  );
  for (const item of oldItems) console.log(`  − ${describeItem(item)}`);
  const linked = oldItems.filter((i) => i.type !== 'DRAFT_ISSUE').length;
  if (linked && !keepOld)
    console.log(
      `  (${linked} из них — issues или pull requests: они уберутся из проекта, но останутся в своих репозиториях)`
    );

  console.log(
    `\nНовых задач: ${TASKS.length} — ${repo ? `issues в ${repo}` : 'черновики в проекте'}`
  );
  for (const stage of STAGE_OPTIONS()) {
    console.log(`  + ${stage.name}: ${TASKS.filter((x) => x.stage === stage.name).length}`);
  }
  console.log(`Поля: ${FIELD_DEFS.map((f) => f.name).join(', ')}`);

  if (!apply) {
    console.log(
      '\nЭто был пробный прогон, ничего не изменено. Чтобы применить:  node umnyaut-roadmap.mjs --apply'
    );
    return;
  }

  if (oldItems.length) {
    const backup = `umnyaut-project-backup-${new Date().toISOString().replace(/[:.]/g, '-')}.json`;
    writeFileSync(backup, JSON.stringify(oldItems, null, 2));
    console.log(`\nБэкап старых задач: ${backup}`);
  }

  if (!keepOld && oldItems.length) {
    console.log('Удаляю старые задачи…');
    oldItems.forEach((item, i) => {
      gql(QUERIES.deleteItem, { project: project.id, item: item.id });
      process.stdout.write(`\r  ${i + 1}/${oldItems.length}`);
    });
    console.log();
  }

  console.log('Готовлю поля…');
  const fields = ensureFields(project);
  const status = pickStatus(project);
  const issues = repo ? existingIssues(repo) : null;
  if (repo) ensureLabel(repo);

  console.log('Создаю задачи…');
  TASKS.forEach((task, i) => {
    let itemId;
    if (repo) {
      let issue = issues.get(task.title);
      if (issue) {
        addLabel(repo, issue.number);
      } else {
        const created = JSON.parse(
          rest([`repos/${repo}/issues`], {
            title: task.title,
            body: task.body,
            labels: [BUSINESS_LABEL.name],
          })
        );
        issue = { nodeId: created.node_id, number: created.number };
      }
      itemId = gql(QUERIES.addItem, { project: project.id, content: issue.nodeId })
        .addProjectV2ItemById.item.id;
    } else {
      itemId = gql(QUERIES.addDraft, { project: project.id, title: task.title, body: task.body })
        .addProjectV2DraftIssue.projectItem.id;
    }

    const values = [
      [
        fields.get(F_TYPE).id,
        { singleSelectOptionId: optionId(fields.get(F_TYPE), TYPE_BUSINESS) },
      ],
      [fields.get(F_STAGE).id, { singleSelectOptionId: optionId(fields.get(F_STAGE), task.stage) }],
      [fields.get(F_AREA).id, { singleSelectOptionId: optionId(fields.get(F_AREA), task.area) }],
      [fields.get(F_START).id, { date: task.start }],
      [fields.get(F_END).id, { date: task.end }],
    ];
    if (task.size)
      values.push([
        fields.get(F_SIZE).id,
        { singleSelectOptionId: optionId(fields.get(F_SIZE), task.size) },
      ]);
    if (status) values.push([status.fieldId, { singleSelectOptionId: status.optionId }]);

    const variables = { project: project.id, item: itemId };
    values.forEach(([fieldId, v], n) => {
      variables[`f${n}`] = fieldId;
      variables[`v${n}`] = v;
    });
    gql(setFieldsMutation(values.length), variables);
    process.stdout.write(`\r  ${i + 1}/${TASKS.length}`);
    sleep(350);
  });

  console.log(`\n\n✔ Готово. Задач в проекте: ${TASKS.length} — ${project.url}`);
  console.log(
    'Роудмап: в проекте «New view» → Roadmap → Date fields: «Начало» и «Срок» → Group by: «Этап».'
  );
}

if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
) {
  try {
    main();
  } catch (error) {
    fail(error.message);
  }
}
